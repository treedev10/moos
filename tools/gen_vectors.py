#!/usr/bin/env python3
"""
Generate src/selftest_vectors.inc: known-answer tests for MOOS's crypto.

    python tools/gen_vectors.py

Expected values come from Python's hashlib/hmac and the 'cryptography'
package - independent implementations - so `net selftest` in MOOS checks its
own SHA-256, HMAC, HKDF, AES, GCM, X25519 and RSA code against them.
"""
import hashlib
import hmac
import os

from cryptography.hazmat.primitives import hashes, serialization
from cryptography.hazmat.primitives.asymmetric import padding, rsa
from cryptography.hazmat.primitives.asymmetric.x25519 import X25519PrivateKey, X25519PublicKey
from cryptography.hazmat.primitives.ciphers import Cipher, algorithms, modes
from cryptography.hazmat.primitives.ciphers.aead import AESGCM

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, "src", "selftest_vectors.inc")


def expand_label(secret, label, context, length):
    full = b"tls13 " + label
    info = length.to_bytes(2, "big") + bytes([len(full)]) + full + bytes([len(context)]) + context
    return hmac.new(secret, info + b"\x01", hashlib.sha256).digest()[:length]


def emit(lines, name, data):
    lines.append("%s:" % name)
    for i in range(0, len(data), 16):
        lines.append("    db " + ", ".join("0x%02X" % b for b in data[i:i + 16]))
    if not data:
        lines.append("    ; (empty)")
    lines.append("%s_len equ %d" % (name, len(data)))


def main():
    v = []
    v.append(("tv_abc", b"abc"))
    v.append(("tv_sha_abc", hashlib.sha256(b"abc").digest()))
    pat = bytes(i * 7 & 0xFF for i in range(200))
    v.append(("tv_pat", pat))
    v.append(("tv_sha_pat", hashlib.sha256(pat).digest()))
    v.append(("tv_hmac_key", b"\x0b" * 20))
    v.append(("tv_hmac_msg", b"Hi There"))
    v.append(("tv_hmac_out", hmac.new(b"\x0b" * 20, b"Hi There", hashlib.sha256).digest()))
    long_key = bytes(range(100))
    v.append(("tv_hmac_lkey", long_key))
    v.append(("tv_hmac_lout", hmac.new(long_key, pat, hashlib.sha256).digest()))
    early = hmac.new(b"\x00" * 32, b"\x00" * 32, hashlib.sha256).digest()
    v.append(("tv_early", early))
    v.append(("tv_derived", expand_label(early, b"derived", hashlib.sha256(b"").digest(), 32)))
    v.append(("tv_ivlabel", expand_label(early, b"iv", b"", 12)))

    aes_key = bytes(range(16))
    aes_pt = bytes.fromhex("00112233445566778899aabbccddeeff")
    enc = Cipher(algorithms.AES(aes_key), modes.ECB()).encryptor()
    v.append(("tv_aes_key", aes_key))
    v.append(("tv_aes_pt", aes_pt))
    v.append(("tv_aes_ct", enc.update(aes_pt) + enc.finalize()))

    gk = bytes((i * 13 + 5) & 0xFF for i in range(16))
    gn = bytes((i * 31 + 1) & 0xFF for i in range(12))
    ga = bytes([0x17, 0x03, 0x03, 0x00, 0x35]) + b"moosAAD!"
    gp = b"MOOS speaks TLS 1.3 now - hello, GitHub!"[:37]
    ct = AESGCM(gk).encrypt(gn, gp, ga)
    v += [("tv_gcm_key", gk), ("tv_gcm_nonce", gn), ("tv_gcm_aad", ga), ("tv_gcm_pt", gp),
          ("tv_gcm_ct", ct[:-16]), ("tv_gcm_tag", ct[-16:])]

    scal = bytes.fromhex("a546e36bf0527c9d3b16154b82465edd62144c0ac1fc5a18506a2244ba449ac4")
    u = bytes.fromhex("e6db6867583030db3594c1a424b15f7c726624ec26b3353b10a903a6d0ab1c4c")
    out = X25519PrivateKey.from_private_bytes(scal).exchange(X25519PublicKey.from_public_bytes(u))
    v += [("tv_x_scalar", scal), ("tv_x_u", u), ("tv_x_out", out)]
    priv = bytes((i * 17 + 3) & 0xFF for i in range(32))
    pub = X25519PrivateKey.from_private_bytes(priv).public_key().public_bytes(
        serialization.Encoding.Raw, serialization.PublicFormat.Raw)
    v += [("tv_x_priv", priv), ("tv_x_pub", pub)]

    # RSA: a fresh 2048-bit key (only its public part is kept), plus a PKCS#1
    # v1.5 signature and a PSS signature over a message, for the verifier.
    key = rsa.generate_private_key(public_exponent=65537, key_size=2048)
    msg = b"MOOS RSA known-answer test"
    pub_n = key.public_key().public_numbers().n.to_bytes(256, "big")
    sig15 = key.sign(msg, padding.PKCS1v15(), hashes.SHA256())
    sigpss = key.sign(msg, padding.PSS(mgf=padding.MGF1(hashes.SHA256()), salt_length=32),
                      hashes.SHA256())
    v += [("tv_rsa_n", pub_n), ("tv_rsa_msg", msg), ("tv_rsa_sig15", sig15),
          ("tv_rsa_sigpss", sigpss), ("tv_rsa_mhash", hashlib.sha256(msg).digest())]
    # raw modular exponentiation check: s^65537 mod n
    s_int = int.from_bytes(sig15, "big")
    v.append(("tv_rsa_pow", pow(s_int, 65537, key.public_key().public_numbers().n).to_bytes(256, "big")))

    lines = ["; selftest_vectors.inc - generated by tools/gen_vectors.py; do not edit.",
             "; Expected values computed with Python hashlib / hmac / cryptography.", "",
             "section .data"]
    for name, data in v:
        emit(lines, name, data)
    lines.append("section .text")
    open(OUT, "w", newline="\n").write("\n".join(lines) + "\n")
    print("wrote", os.path.relpath(OUT, ROOT), "with", len(v), "vectors")


if __name__ == "__main__":
    main()
