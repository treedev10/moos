#!/usr/bin/env python3
"""
Generate src/crypto_tables.inc: the constant tables MOOS's crypto code needs.

    python tools/gen_tables.py

The values are computed from their mathematical definitions (not typed in),
then checked: the SHA-256 constants are used in a small Python SHA-256 that
must match hashlib, and the AES S-box is checked against known entries.
"""
import hashlib
import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, "src", "crypto_tables.inc")


def primes(n):
    out, k = [], 2
    while len(out) < n:
        if all(k % p for p in out if p * p <= k):
            out.append(k)
        k += 1
    return out


def iroot(x, n):
    """floor(x ** (1/n)) for big integers."""
    lo, hi = 0, 1 << ((x.bit_length() + n - 1) // n + 1)
    while lo < hi:
        mid = (lo + hi + 1) // 2
        if mid ** n <= x:
            lo = mid
        else:
            hi = mid - 1
    return lo


# SHA-256: K = first 32 bits of the fractional parts of the cube roots of the
# first 64 primes; IV = same for the square roots of the first 8 primes.
SHA_K = [iroot(p << 96, 3) & 0xFFFFFFFF for p in primes(64)]
SHA_IV = [iroot(p << 64, 2) & 0xFFFFFFFF for p in primes(8)]


def py_sha256(msg):
    def ror(x, n):
        return ((x >> n) | (x << (32 - n))) & 0xFFFFFFFF
    h = list(SHA_IV)
    ml = len(msg) * 8
    msg = msg + b"\x80" + b"\0" * ((55 - len(msg)) % 64) + ml.to_bytes(8, "big")
    for off in range(0, len(msg), 64):
        w = [int.from_bytes(msg[off + 4 * i: off + 4 * i + 4], "big") for i in range(16)]
        for i in range(16, 64):
            s0 = ror(w[i - 15], 7) ^ ror(w[i - 15], 18) ^ (w[i - 15] >> 3)
            s1 = ror(w[i - 2], 17) ^ ror(w[i - 2], 19) ^ (w[i - 2] >> 10)
            w.append((w[i - 16] + s0 + w[i - 7] + s1) & 0xFFFFFFFF)
        a, b, c, d, e, f, g, hh = h
        for i in range(64):
            t1 = (hh + (ror(e, 6) ^ ror(e, 11) ^ ror(e, 25)) + ((e & f) ^ (~e & g))
                  + SHA_K[i] + w[i]) & 0xFFFFFFFF
            t2 = ((ror(a, 2) ^ ror(a, 13) ^ ror(a, 22)) + ((a & b) ^ (a & c) ^ (b & c))) & 0xFFFFFFFF
            a, b, c, d, e, f, g, hh = (t1 + t2) & 0xFFFFFFFF, a, b, c, (d + t1) & 0xFFFFFFFF, e, f, g
        h = [(x + y) & 0xFFFFFFFF for x, y in zip(h, [a, b, c, d, e, f, g, hh])]
    return b"".join(x.to_bytes(4, "big") for x in h)


def gf_mul(a, b):
    r = 0
    while b:
        if b & 1:
            r ^= a
        a <<= 1
        if a & 0x100:
            a ^= 0x11B
        b >>= 1
    return r


def aes_sbox():
    box = []
    for x in range(256):
        inv = 0 if x == 0 else next(y for y in range(1, 256) if gf_mul(x, y) == 1)
        s = inv
        for i in range(1, 5):
            s ^= ((inv << i) | (inv >> (8 - i))) & 0xFF
        box.append(s ^ 0x63)
    return box


def main():
    for m in (b"", b"abc", b"x" * 1000):
        assert py_sha256(m) == hashlib.sha256(m).digest(), "SHA-256 constants wrong"
    sbox = aes_sbox()
    assert sbox[0x00] == 0x63 and sbox[0x01] == 0x7C and sbox[0x53] == 0xED and sbox[0xFF] == 0x16

    lines = ["; crypto_tables.inc - generated by tools/gen_tables.py; do not edit by hand.",
             "; Values are computed from their definitions and self-checked.", "",
             "section .data", "align 4", "sha256_k:"]
    for i in range(0, 64, 8):
        lines.append("    dd " + ", ".join("0x%08X" % v for v in SHA_K[i:i + 8]))
    lines.append("sha256_iv:")
    lines.append("    dd " + ", ".join("0x%08X" % v for v in SHA_IV))
    lines.append("aes_sbox:")
    for i in range(0, 256, 16):
        lines.append("    db " + ", ".join("0x%02X" % v for v in sbox[i:i + 16]))
    lines.append("section .text")
    open(OUT, "w", newline="\n").write("\n".join(lines) + "\n")
    print("wrote", os.path.relpath(OUT, ROOT), "(checked against hashlib)")


if __name__ == "__main__":
    main()
